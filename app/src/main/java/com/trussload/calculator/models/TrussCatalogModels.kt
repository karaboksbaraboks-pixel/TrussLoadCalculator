package com.trussload.calculator.models

// ============================================================
// ТИП НАГРУЗКИ
// ============================================================

enum class LoadType(
    val title: String
) {

    UDL(
        "Равномерно распределённая"
    ),

    POINT_CENTER(
        "Точечная по центру"
    ),

    TWO_POINT(
        "Две симметричные точечные"
    )
}

// ============================================================
// ЭЛЕМЕНТ КАТАЛОГА ФЕРМ
// ============================================================

data class TrussCatalogItem(

    // --------------------------------------------------------
    // ИДЕНТИФИКАЦИЯ
    // --------------------------------------------------------

    val manufacturer: String,

    val series: String,

    val model: String,

    // --------------------------------------------------------
    // ГАБАРИТЫ
    // --------------------------------------------------------

    val heightMm: Int,

    val widthMm: Int,

    // --------------------------------------------------------
    // МАССА
    // --------------------------------------------------------

    val weightKgPerMeter: Double,

    // --------------------------------------------------------
    // ПАСПОРТНЫЕ ДАННЫЕ ПРОИЗВОДИТЕЛЯ
    // --------------------------------------------------------

    val maxSpanM: Double? = null,

    val maxUdlKgPerM: Double? = null,

    val maxCenterPointKg: Double? = null,

    // --------------------------------------------------------
    // МАТЕРИАЛ
    // --------------------------------------------------------

    val material: String =
        "EN AW-6082 T6",

    /*
     * Модуль упругости материала.
     *
     * Единица:
     * ГПа
     *
     * Пока nullable, потому что существующий каталог
     * может не содержать проверенного значения.
     */
    val elasticModulusGPa: Double? = null,

    // --------------------------------------------------------
    // ОСНОВНЫЕ ПОЯСА ФЕРМЫ
    //
    // Эти параметры описывают именно основные
    // продольные трубы фермы.
    //
    // Они НЕ должны автоматически подменяться
    // размерами раскосов.
    // --------------------------------------------------------

    /*
     * Количество основных продольных поясов.
     *
     * Например:
     * плоская ферма     -> 2
     * треугольная      -> 3
     * квадратная       -> 4
     */
    val mainChordCount: Int? = null,

    /*
     * Наружный диаметр трубы основного пояса, мм.
     */
    val mainChordOuterDiameterMm: Double? = null,

    /*
     * Толщина стенки трубы основного пояса, мм.
     */
    val mainChordWallThicknessMm: Double? = null,

    // --------------------------------------------------------
    // ЭКВИВАЛЕНТНАЯ ПЛОЩАДЬ
    //
    // Это отдельное поле для расчётной модели.
    //
    // Не заполняем его автоматически без определения
    // принятой расчётной схемы.
    // --------------------------------------------------------

    val equivalentAxialAreaM2: Double? = null,

    // --------------------------------------------------------
    // ДОПОЛНИТЕЛЬНАЯ ИНФОРМАЦИЯ
    // --------------------------------------------------------

    val description: String = "",

    val source: String = ""
)

// ============================================================
// ВХОДНЫЕ ДАННЫЕ ПРОВЕРКИ ПО ПАСПОРТУ
// ============================================================

data class TrussCheckInput(

    val spanM: Double,

    val loadKg: Double,

    val loadType: LoadType,

    val selectedTruss:
        TrussCatalogItem? = null
)

// ============================================================
// РЕЗУЛЬТАТ ПРОВЕРКИ ПО ПАСПОРТУ
// ============================================================

data class TrussCheckResult(

    val utilizationPercent:
        Double?,

    val isWithinLimit:
        Boolean?,

    val allowableLoadKg:
        Double?,

    val message:
        String
)
